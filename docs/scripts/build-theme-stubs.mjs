#!/usr/bin/env node

/**
 * Generates vars-only theme stubs for the docs app.
 *
 * Each src/themes/*.scss ships an optional `@use "tailwindcss"` and an
 * `@theme { ... }` block for downstream Tailwind consumers. Neither may
 * reach the docs theme bundles: the tailwindcss import duplicates the
 * base layer already injected by the `default` bundle (~79 kB per
 * theme), and `@theme` compiled outside a Tailwind context emits an
 * unlayered self-referential `:root, :host` block that invalidates
 * every custom property it names. The stubs emitted here keep only the
 * literal CSS (the `:root` token block plus any theme-specific rules).
 *
 * The `default` stub is NOT generated — it must keep the full Tailwind
 * base/utilities layer, which src/themes/default.scss imports itself.
 */

import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join, basename } from "path";
import { fileURLToPath } from "url";

const here = fileURLToPath(new URL(".", import.meta.url));
const STUB_DIR = join(here, "../src/styles/themes");
const SRC_DIR = join(here, "../../src/themes");

function stripThemeBlock(content) {
  const start = content.search(/@theme\s*\{/);
  if (start === -1) return content;
  let i = content.indexOf("{", start);
  let depth = 0;
  do {
    if (content[i] === "{") depth++;
    else if (content[i] === "}") depth--;
    i++;
  } while (depth > 0 && i < content.length);
  return content.slice(0, start) + content.slice(i);
}

const stubs = readdirSync(STUB_DIR).filter(
  (f) => f.endsWith(".scss") && f !== "default.scss"
);

for (const stub of stubs) {
  const id = basename(stub, ".scss");
  let content = readFileSync(join(SRC_DIR, `${id}.scss`), "utf-8");
  content = content.replace(/@use\s+["']tailwindcss["'];?\n?/g, "");
  content = stripThemeBlock(content).trimEnd() + "\n";
  writeFileSync(
    join(STUB_DIR, stub),
    `// GENERATED by docs/scripts/build-theme-stubs.mjs from src/themes/${id}.scss — do not edit\n${content}`
  );
}

console.log(`✓ Generated ${stubs.length} vars-only theme stubs`);
